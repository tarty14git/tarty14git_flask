-- Oracle Database DDL Schema for com.cth Enterprise Application

CREATE TABLE users (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(100) NOT NULL UNIQUE,
    email VARCHAR2(150) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    full_name VARCHAR2(150),
    is_admin NUMBER(1) DEFAULT 0,
    is_locked NUMBER(1) DEFAULT 0,
    failed_attempts NUMBER DEFAULT 0,
    password_expiry_date TIMESTAMP,
    otp_code VARCHAR2(10),
    otp_expiry TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE roles (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR2(50) NOT NULL UNIQUE,
    description VARCHAR2(255)
);

CREATE TABLE user_roles (
    user_id NUMBER REFERENCES users(id) ON DELETE CASCADE,
    role_id NUMBER REFERENCES roles(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE audit_logs (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(100),
    action VARCHAR2(100) NOT NULL,
    details VARCHAR2(1000),
    ip_address VARCHAR2(45),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE report_configs (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    description VARCHAR2(255),
    table_name VARCHAR2(100) NOT NULL,
    selected_fields VARCHAR2(1000) NOT NULL,
    where_clause VARCHAR2(500),
    order_by VARCHAR2(200),
    created_by VARCHAR2(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE system_settings (
    setting_key VARCHAR2(100) PRIMARY KEY,
    setting_value VARCHAR2(500) NOT NULL,
    description VARCHAR2(255)
);

